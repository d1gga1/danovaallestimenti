def sitemap(tutte):
    s = s0 = leggi("sitemap.xml")
    for L, p in tutte:
        url = f"{SITO}/{p['path']}/"
        if f"<loc>{url}</loc>" in s: continue
        alts, xd = alts_cluster(p["cluster"])
        righe = "".join(f'\n    <xhtml:link rel="alternate" hreflang="{a}" href="{u}"/>' for a, u in alts) + f'\n    <xhtml:link rel="alternate" hreflang="x-default" href="{xd}"/>'
        ent = (f"  <url>\n    <loc>{url}</loc>\n    <lastmod>{OGGI}</lastmod>\n"
               f"    <image:image><image:loc>{SITO}/assets/img/stand/{p['img']}-1200.webp</image:loc></image:image>\n"
               f"    <image:image><image:loc>{SITO}/assets/img/stand/og/{p['img']}.jpg</image:loc></image:image>{righe}\n  </url>\n")
        s = s.replace("</urlset>", ent + "</urlset>")
    return scrivi("sitemap.xml", s) if s != s0 else False


