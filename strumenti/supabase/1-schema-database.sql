-- DANOVA STAND — database su Supabase per l'area privata (danovastand.com/private_area/).
-- Statistiche visite, profili dei visitatori, azioni (WhatsApp, telefono, email…) e richieste dei moduli.
-- Stessa struttura usata per Pan.door.a, senza le tabelle dello shop.
-- Tutte le tabelle hanno la RLS attiva e NESSUNA regola pubblica: le legge e le scrive solo la
-- Edge Function "ds". Dal browser non sono accessibili.
-- Si può lanciare più volte senza problemi.

create table if not exists public.limiti_c (k text, ts bigint);
create index if not exists i_lim on public.limiti_c (k, ts);

-- visitatori (codice anonimo); nome, email e telefono solo se li lasciano in un modulo
create table if not exists public.visitatori (
  id text primary key, primo bigint, ultimo bigint, sessioni int,
  email text, nome text, telefono text, cliente_id bigint,
  fonte text,          -- richiesta (modulo del sito)
  identificato bigint  -- quando è diventato un contatto noto
);
create index if not exists i_vis_email on public.visitatori (email);
create index if not exists i_vis_ultimo on public.visitatori (ultimo);

-- visite (nessun indirizzo IP viene salvato)
create table if not exists public.sessioni (
  id text primary key, visitatore text, inizio bigint, ultimo bigint, giorno text, ora int, dow int,
  ritorno int, n_visita int, cc text, paese text, regione text, citta text, cap text, geo_fonte text,
  lat double precision, lon double precision,
  gps_lat double precision, gps_lon double precision, gps_acc int, gps_indirizzo text, gps_citta text, gps_cap text, gps_ts bigint,
  canale text, sorgente text, ref_host text, campagna text, ingresso text, pagina text, titolo text,
  dispositivo text, browser text, so text, lingua text, pagine int default 0, chiuso int default 0,
  isp text, fuso text, schermo text, finestra text, dpr real, touch int, connessione text, memoria real, cpu int,
  tema text, lingue text, riferimento text, utm_sorgente text, utm_mezzo text, utm_termine text, ua text,
  azioni int default 0, modello text, so_versione text, visitatore_noto int default 0, consenso int
);
create index if not exists i_s_giorno on public.sessioni (giorno);
create index if not exists i_s_ultimo on public.sessioni (ultimo);
create index if not exists i_s_vis on public.sessioni (visitatore);

create table if not exists public.visualizzazioni (
  id bigint generated by default as identity primary key,
  sessione text, ts bigint, giorno text, ora int, percorso text, titolo text, scroll int, tempo int
);
create index if not exists i_v_giorno on public.visualizzazioni (giorno);
create index if not exists i_v_sess on public.visualizzazioni (sessione);

-- azioni: WhatsApp, telefono, email, richieste, download, clic (solo con consenso cookie)…
create table if not exists public.eventi (
  id bigint generated by default as identity primary key,
  sessione text, visitatore text, ts bigint, giorno text, ora int,
  tipo text, dettaglio text, percorso text, titolo text
);
create index if not exists i_e_giorno on public.eventi (giorno);
create index if not exists i_e_tipo on public.eventi (tipo);
create index if not exists i_e_sess on public.eventi (sessione);
create index if not exists i_e_vis on public.eventi (visitatore);

-- richieste dei moduli (contatti e "Richiedi lo stand"): copia di quello che arriva via email
create table if not exists public.richieste (
  id bigint generated by default as identity primary key, creato bigint, aggiornato bigint,
  stato text default 'nuova',          -- nuova / contattato / preventivo / acquisita / persa
  nome text, email text, telefono text, azienda text, fiera text, urgenza text, messaggio text, oggetto text,
  campi text,                          -- altri campi del modulo (metri quadri, tipo di spazio…)
  pagina text, titolo text, lingua text,
  rif text,                            -- codice "Rif." del visitatore (lo stesso dei messaggi WhatsApp)
  visitatore text, sessione text,      -- collegamento alla scheda Persone
  citta text, regione text, paese text, cc text, canale text, sorgente text,
  valore numeric(12,2), note_admin text, contattato bigint
);
create index if not exists i_r_creato on public.richieste (creato);
create index if not exists i_r_stato on public.richieste (stato);
create index if not exists i_r_vis on public.richieste (visitatore);

-- sicurezza: RLS attiva ovunque, nessuna regola => anon e utenti loggati non vedono nulla
do $$
declare t text;
begin
  foreach t in array array['limiti_c','visitatori','sessioni','visualizzazioni','eventi','richieste']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end $$;

select 'ok: tabelle create' as esito;
