def patch_cluster(src):
    """Aggiunge ur e hi agli hreflang e al selettore lingua delle pagine sorelle gia' esistenti."""
    alts, _ = alts_cluster(src)
    slug = src.split("/", 1)[1]; n = 0
    nuovi = [(L, f"{SITO}/{L}/{slug}/") for L in LINGUE]
    for h, u in alts:
        if h in LINGUE: continue
        rel = u.replace(SITO + "/", "") + "index.html"
        if not os.path.exists(os.path.join(ROOT, rel)): continue
        s = s0 = leggi(rel)
        for L, nu in nuovi:
            if f'hreflang="{L}"' not in s.split("</head>")[0]:
                s = s.replace('<link rel="alternate" hreflang="x-default"', f'<link rel="alternate" hreflang="{L}" href="{nu}">\n<link rel="alternate" hreflang="x-default"', 1)
        def add(m):
            blocco = m.group(0)
            if 'hreflang="ur"' in blocco: return blocco
            ind = re.search(r"\n(\s*)<a ", blocco).group(1)
            extra = "".join(f'\n{ind}<a href="/{L}/{slug}/" hreflang="{L}">{CODICE[L]}</a>' for L in LINGUE)
            return re.sub(r"(</a>)(\s*</(?:span|div)>)$", lambda x: x.group(1) + extra + x.group(2), blocco)
        s = re.sub(r'<span class="lang-links">.*?</span>', add, s, 1, flags=re.S)
        s = re.sub(r'<div class="mob-lang-links">.*?</div>', add, s, 1, flags=re.S)
        if s != s0: scrivi(rel, s); n += 1
    return n


